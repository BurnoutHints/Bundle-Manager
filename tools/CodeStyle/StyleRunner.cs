using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.MSBuild;
using Microsoft.CodeAnalysis.Text;
using System.Text;
using System.Text.RegularExpressions;
using System.Collections.Concurrent;

namespace CodeStyle;

internal static class StyleRunner
{
    private static readonly UTF8Encoding strictUTF8 = new(false, true);

    public static async Task<int> RunAsync(CommandOptions options)
    {
        string directory = Path.GetDirectoryName(options.Workspace)!;
        using MSBuildWorkspace workspace = MSBuildWorkspace.Create();
        ConcurrentQueue<string> failures = new();
        using WorkspaceEventRegistration registration = workspace.RegisterWorkspaceFailedHandler(e =>
        {
            if (e.Diagnostic.Kind == WorkspaceDiagnosticKind.Failure &&
                !(e.Diagnostic.Message.Contains("Package '", StringComparison.Ordinal) && e.Diagnostic.Message.Contains("was restored using", StringComparison.Ordinal)))
                failures.Enqueue(e.Diagnostic.Message);
        }, null);
        Solution solution = Path.GetExtension(options.Workspace) == ".csproj"
            ? (await workspace.OpenProjectAsync(options.Workspace)).Solution
            : await workspace.OpenSolutionAsync(options.Workspace);

        if (failures.Count > 0)
            throw new InvalidOperationException("Cannot load the workspace. Restore its packages first.\n" + string.Join("\n", failures));

        List<DocumentId> documents = [];
        HashSet<DocumentId> generatedDocuments = [];

        foreach (Document document in solution.Projects.Where(project => project.Language == LanguageNames.CSharp).SelectMany(project => project.Documents))
        {
            if (!Included(document.FilePath, directory, options.Includes))
                continue;

            SyntaxTree tree = (await document.GetSyntaxTreeAsync())!;
            StyleSettings settings = new(document.Project.AnalyzerOptions.AnalyzerConfigOptionsProvider.GetOptions(tree));

            bool generated = settings.Generated || document.FilePath!.EndsWith(".Designer.cs", StringComparison.OrdinalIgnoreCase) ||
                document.FilePath.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) || tree.GetRoot().GetLeadingTrivia().Any(trivia =>
                (trivia.IsKind(SyntaxKind.SingleLineCommentTrivia) || trivia.IsKind(SyntaxKind.MultiLineCommentTrivia)) &&
                trivia.ToString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase));

            if (!settings.Excluded && (!generated || settings.FormatGenerated))
            {
                byte[] bytes = await File.ReadAllBytesAsync(document.FilePath!);

                if (!IsUTF8(bytes) && bytes is not ([0xFF, 0xFE, ..] or [0xFE, 0xFF, ..] or [0, 0, 0xFE, 0xFF, ..]))
                    throw new InvalidOperationException("Cannot safely decode " + document.FilePath + ". Save it as UTF-8 before formatting.");

                documents.Add(document.Id);

                if (generated)
                    generatedDocuments.Add(document.Id);
            }
        }

        if (documents.Count == 0)
            throw new InvalidOperationException("No maintained C# documents matched the selected workspace and paths.");

        string[] diagnostics = await DiagnosticsAsync(solution, directory);
        bool standardFailed = false;
        DocumentId[] standardDocuments = [.. documents.Where(id => !generatedDocuments.Contains(id))];

        if (diagnostics.Length > 0 && standardDocuments.Length > 0)
        {
            List<string> arguments = ["format", "style", options.Workspace, "--no-restore", "--severity", "info", "--verbosity", "quiet", "--diagnostics", .. diagnostics, "--include"];
            arguments.AddRange(standardDocuments.Select(id => Path.GetRelativePath(directory, solution.GetDocument(id)!.FilePath!)).Distinct());

            if (!options.Fix)
                arguments.Add("--verify-no-changes");

            ProcessResult result = await ProcessRunner.RunAsync("dotnet", arguments, directory, true);

            if (result.ExitCode is not (0 or 2))
                throw new InvalidOperationException("The standard C# style check could not complete. Restore and build the workspace, then retry.");

            standardFailed = result.ExitCode != 0;
        }

        foreach (DocumentId id in documents)
        {
            Document document = solution.GetDocument(id)!;
            solution = solution.WithDocumentText(id, SourceText.From(await File.ReadAllTextAsync(document.FilePath!)));
        }

        Dictionary<string, HashSet<string>> handlers = NamingRules.EventBindings(await Task.WhenAll(solution.Projects
            .Where(project => project.Language == LanguageNames.CSharp).SelectMany(project => project.Documents)
            .Select(async document => (await document.GetSyntaxRootAsync())!)));
        List<StyleIssue> issues = [];
        HashSet<string> visited = new(OperatingSystem.IsWindows()
            ? StringComparer.OrdinalIgnoreCase
            : StringComparer.Ordinal);
        int changed = 0;

        foreach (DocumentId id in documents)
        {
            Document document = solution.GetDocument(id)!;
            string path = document.FilePath!;

            if (!visited.Add(path))
                continue;

            SyntaxNode root = (await document.GetSyntaxRootAsync())!;
            SyntaxTree tree = root.SyntaxTree;
            StyleSettings settings = new(document.Project.AnalyzerOptions.AnalyzerConfigOptionsProvider.GetOptions(tree));
            Diagnostic[] syntaxErrors = [.. root.GetDiagnostics().Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)];

            if (syntaxErrors.Length > 0)
            {
                issues.AddRange(syntaxErrors.Select(error => new StyleIssue(path, error.Location.GetLineSpan().StartLinePosition.Line + 1, 1, "STYLE002", error.GetMessage())));
                continue;
            }

            SourceText original = await document.GetTextAsync();
            SourceText formatted = await StyleFormatter.FormatAsync(document, settings);
            byte[] bytes = await File.ReadAllBytesAsync(path);
            bool hasBOM = bytes is [0xEF, 0xBB, 0xBF, ..];

            if (!original.ContentEquals(formatted) || hasBOM != settings.EmitBOM || !IsUTF8(bytes))
            {
                changed++;

                if (options.Fix)
                {
                    await File.WriteAllTextAsync(path, formatted.ToString(), new UTF8Encoding(settings.EmitBOM));
                    Console.WriteLine("Fixed " + Path.GetRelativePath(directory, path));
                    document = document.WithText(formatted);
                    root = (await document.GetSyntaxRootAsync())!;
                }
                else
                {
                    int first = 0;

                    while (first < Math.Min(original.Length, formatted.Length) && original[first] == formatted[first])
                        first++;

                    LinePosition position = original.Lines.GetLinePosition(first);
                    issues.Add(new(path, position.Line + 1, position.Character + 1, "STYLE001", "Formatting differs from the configured style. Run CodeStyle fix."));
                }
            }

            if (!generatedDocuments.Contains(id))
                issues.AddRange(NamingRules.Check(root, path, settings, handlers));
        }

        foreach (StyleIssue issue in issues)
            Console.Error.WriteLine(issue);

        Console.WriteLine($"CodeStyle: {visited.Count} files, {changed} {(options.Fix
            ? "formatted"
            : "needing formatting")}, {issues.Count} issues.");
        return issues.Count > 0 || standardFailed
            ? 1
            : 0;
    }

    private static bool Included(string? path, string directory, string[] includes)
    {
        if (path == null || !File.Exists(path))
            return false;

        string relative = Path.GetRelativePath(directory, path);
        string[] segments = relative.Replace('\\', '/').Split('/');

        if (segments[0] == ".." || segments.Any(segment => segment is "bin" or "obj" or "artifacts" or ".git" or ".vs"))
            return false;

        StringComparison comparison = OperatingSystem.IsWindows()
            ? StringComparison.OrdinalIgnoreCase
            : StringComparison.Ordinal;
        return includes.Length == 0 || includes.Any(include => path.Equals(include, comparison) || path.StartsWith(include.TrimEnd(Path.DirectorySeparatorChar) + Path.DirectorySeparatorChar, comparison));
    }

    private static async Task<string[]> DiagnosticsAsync(Solution solution, string directory)
    {
        HashSet<string> diagnostics = [];
        HashSet<string> configurations = [];

        foreach (AnalyzerConfigDocument document in solution.Projects.SelectMany(project => project.AnalyzerConfigDocuments))
            if (Path.GetFileName(document.FilePath) == ".editorconfig")
                configurations.Add((await document.GetTextAsync()).ToString());

        for (DirectoryInfo? current = new(directory); current != null; current = current.Parent)
        {
            string path = Path.Combine(current.FullName, ".editorconfig");

            if (!File.Exists(path))
                continue;

            string configuration = File.ReadAllText(path);
            configurations.Add(configuration);

            if (Regex.IsMatch(configuration, @"(?m)^root\s*=\s*true\s*$"))
                break;
        }

        foreach (string configuration in configurations)
            foreach (Match match in Regex.Matches(configuration, @"dotnet_diagnostic\.(IDE\d+)\.severity\s*=\s*(suggestion|warning|error)"))
                if (match.Groups[1].Value != "IDE1006")
                    diagnostics.Add(match.Groups[1].Value);

        return [.. diagnostics.Order()];
    }

    private static bool IsUTF8(byte[] bytes)
    {
        try
        {
            strictUTF8.GetCharCount(bytes);
            return true;
        }
        catch (DecoderFallbackException)
        {
            return false;
        }
    }
}
